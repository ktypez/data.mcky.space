const characterThemes: Theme[] = [dusk, glitchpage, crt, claude, rack, noc, min, brut, mcky, blueprint, noir]

export const themes: Theme[] = [...baseThemes, ...characterThemes]

const defaultTheme: Theme = dusk

/** Resolve a theme by id, falling back to the default. */
export function getTheme(id: string | undefined | null): Theme {
  return themes.find((t) => t.id === id) ?? defaultTheme
}

/** Full-character themes (vs the plain/legacy bubblegum). All themes own a
 *  static stylesheet now; this only drives picker grouping/labels. */
export function isCharacterTheme(t: Theme): boolean {
  return !!t.character && t.character !== 'plain'
}

/** Dark-only themes force the .dark class regardless of user mode. */
export function isDarkOnlyTheme(t: Theme): boolean {
  return !!t.modes && t.modes.length === 1 && t.modes[0] === 'dark'
}

/** Light-only themes never support dark mode. */
export function isLightOnlyTheme(t: Theme): boolean {
  return !!t.modes && t.modes.length === 1 && t.modes[0] === 'light'
}

/** Theme supports both light and dark modes. */
export function isDualModeTheme(t: Theme): boolean {
  return !!t.modes && t.modes.length === 2
}

