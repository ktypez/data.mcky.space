#!/usr/bin/env node
/**
 * Regenerates src/v3/lib/css-presets.ts from tweakcn's public preset roster.
 * Source: https://github.com/jnsahaj/tweakcn (utils/theme-presets.ts)
 *
 * Usage:  node scripts/gen-css-presets.mjs [--url <raw-ts-url>]
 *
 * Notes:
 * - Only color/radius tokens are emitted. tweakcn's font tokens (--font-sans)
 *   are skipped on purpose: v3.css sets font-family explicitly and Thai text
 *   needs the Sarabun/Noto fallback chain. Chart/shadow/spacing tokens are
 *   dropped too — v3 has no charts and owns its press/shadow feel.
 * - Output is generated code; rerun this script to refresh the roster.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import path from 'node:path'

const argv = process.argv
const urlIdx = argv.indexOf('--url')
const SRC_URL =
  urlIdx > -1 && argv[urlIdx + 1]
    ? argv[urlIdx + 1]
    : 'https://raw.githubusercontent.com/jnsahaj/tweakcn/main/utils/theme-presets.ts'

const OUT = path.resolve(import.meta.dirname, '../src/v3/lib/css-presets.ts')

// Fetch the TS source and coerce it into a bare object literal we can eval.
const raw = execFileSync('curl', ['-fsSL', SRC_URL], { encoding: 'utf8' })
const objSrc = raw
  .replace(/^import[^;]+;\s*/m, '')
  .replace(/export const defaultPresets[^=]*=\s*/, '')
  .trim()
  .replace(/;+$/, '')

const presets = new Function(`return (${objSrc})`)()

/** Tokens we drop — see header comment. */
const DROP = new Set([
  'font-sans', 'font-serif', 'font-mono',
  'chart-1', 'chart-2', 'chart-3', 'chart-4', 'chart-5',
  'shadow-color', 'shadow-opacity', 'shadow-blur', 'shadow-spread',
  'shadow-offset-x', 'shadow-offset-y', 'letter-spacing', 'spacing',
])

function block(selector, styles) {
  const decls = Object.entries(styles)
    .filter(([k]) => !DROP.has(k))
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n')
  return `${selector} {\n${decls}\n}`
}

const entries = Object.entries(presets).map(([id, p]) => ({
  id,
  label: p.label ?? id,
  css: `${block(':root', p.styles.light)}\n\n${block('.dark', p.styles.dark)}\n`,
}))

const body = entries
  .map(
    (e) =>
      `  {\n    id: ${JSON.stringify(e.id)},\n    label: ${JSON.stringify(e.label)},\n    css: ${JSON.stringify(e.css)},\n  },`,
  )
  .join('\n')

const file = `/**
 * Baked-in CSS presets from tweakcn (https://tweakcn.com/themes).
 * GENERATED by scripts/gen-css-presets.mjs — do not edit by hand.
 * Roster source: ${SRC_URL}
 *
 * Loaded via dynamic import() only when the custom-theme dialog opens,
 * so first paint never pays for this file.
 */
export interface CssPreset {
  id: string
  label: string
  css: string
}

export const CSS_PRESETS: CssPreset[] = [
${body}
]
`

writeFileSync(OUT, file)
console.log(`wrote ${OUT}: ${entries.length} presets, ${Math.round(file.length / 1024)} KB source`)
